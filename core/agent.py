class AgentState(TypedDict):
    """The shared state of the customer support agent."""
    company_id: str
    customer_id: Optional[str]
    query: str
    messages: List[BaseMessage]
    tools_results: List[Dict[str, Any]]
    sources: List[Dict[str, Any]]
    steps: int
    max_steps: int
    plan: NotRequired[Dict[str, Any]]
    final_response: str


class Plan(BaseModel):
    """Structured plan generated by planner LLM."""
    action: Literal["tool", "finish"] = Field(
        description="Select 'tool' if you need more evidence or data, or 'finish' if you have sufficient verified evidence to answer."
    )
    tool_name: Optional[str] = Field(
        default=None,
        description="The exact name of the tool to call if action is 'tool'."
    )
    tool_args: Dict[str, Any] = Field(
        default_factory=dict,
        description="Arguments to pass to the tool."
    )
    reasoning_summary: str = Field(
        description="Brief summary of why this action was chosen."
    )


