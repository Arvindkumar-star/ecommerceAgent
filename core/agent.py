def plan_step(state: AgentState) -> Dict[str, Any]:
    """
    Planner Node: Inspects state, query, and previous tool results.
    Decides whether to execute another tool or finish.
    """
    llm = get_llm()
    planner_llm = llm.with_structured_output(Plan)

    tool_descriptions = "\n".join([f"- {t['name']}: {t['description']}" for t in AVAILABLE_TOOLS])

    prompt = f"""You are an intelligent, grounded AI customer support agent for company '{state['company_id']}'.

Customer Query: {state['query']}
Authenticated Customer ID: {state.get('customer_id') or 'Anonymous / Guest'}

Previous Tool Results: {state['tools_results']}

Available Tools:
{tool_descriptions}

Rules:
1. Call a relevant tool ONLY if you need verified operational data or policy documents.
2. Select 'finish' as soon as you have sufficient verified evidence to answer the customer's query, or if the necessary integration/document is reported as unconfigured or unavailable.
3. NEVER invent or fabricate data, order status, inventory, policies, or return windows.
4. If the user asks about an order but did not provide an order ID, finish and politely ask them for the order ID.
5. If an integration reports 'unconfigured', finish and clearly inform the user that the system is currently unconfigured.
"""

    plan = invoke_llm_with_fallback(prompt, structured_class=Plan)

    if plan.action == "tool" and plan.tool_name not in TOOL_NAMES:
        return {
            "plan": {"action": "finish", "tool_name": None, "tool_args": {}, "reasoning_summary": "Invalid tool requested"},
            "steps": state["steps"] + 1
        }

    return {
        "plan": plan.model_dump(),
        "steps": state["steps"] + 1
    }


def run_tool(state: AgentState) -> Dict[str, Any]:
    """
    Tool Execution Node: Executes planned tool and updates state evidence and sources.
    """
    plan = state.get("plan", {})
    tool_name = plan.get("tool_name")
    tool_args = plan.get("tool_args", {})

    result = execute_tool_with_context(
        tool_name=tool_name,
        tool_args=tool_args,
        company_id=state["company_id"],
        customer_id=state.get("customer_id")
    )

    results = list(state["tools_results"]) + [result]
    sources = list(state["sources"])

    # Extract source citations from tool result
    tool_data = result.get("data", {})
    if isinstance(tool_data, dict):
        # From knowledge_base chunks
        if "chunks" in tool_data:
            for c in tool_data["chunks"]:
                sources.append({
                    "type": "document",
                    "filename": c.get("filename"),
                    "location": c.get("location"),
                    "content": c.get("content"),
                    "score": c.get("score")
                })
        # From return eligibility citations
        if "citations" in tool_data:
            for c in tool_data["citations"]:
                sources.append({
                    "type": "document",
                    "filename": c.get("filename"),
                    "location": c.get("location"),
                    "content": c.get("excerpt")
                })
        # From live operational APIs
        if result.get("source") in ["orders_api", "inventory_api"]:
            sources.append({
                "type": "operational",
                "source": result.get("source"),
                "status": tool_data.get("status"),
                "retrieved_at": tool_data.get("retrieved_at")
            })

    return {
        "tools_results": results,
        "sources": sources
    }


def respond(state: AgentState) -> Dict[str, Any]:
    """
    Responder Node: Synthesizes final answer grounded exclusively in verified evidence.
    """
    llm = get_llm()

    evidence_summary = []
    for r in state["tools_results"]:
        tool = r.get("tool", "unknown")
        data = r.get("data", {})
        evidence_summary.append(f"Tool [{tool}]: {data}")

    system_prompt = """You are NexusCX AI, an intelligent, professional customer support assistant for enterprise commerce.
Answer the user's question clearly, warmly, and accurately, grounded strictly in the verified evidence provided.

Formatting & Style Guidelines:
1. Begin with a direct, courteous 1-sentence summary answering their core question.
2. Structure policy rules or conditions into clean, organized sections using bullet points with bold labels (e.g., "* **Return Window:** 30 days from confirmed delivery.").
3. For distinct topics (such as Non-Returnable Items or Restocking Fees), group them cleanly so the customer can read at a glance without cluttered nested asterisks.
4. Bold key numbers, timelines, fees, and requirements so they stand out clearly.
5. Grounding & Citations: Naturally cite the verified document name and page number (e.g., *(Source: sample_company_policy.pdf, Page 1)*).
6. Strict Grounding: ONLY state facts that are explicitly verified in the tool results. If an integration or policy is unavailable or unconfigured, clearly explain that without guessing.
"""

    user_prompt = f"""Customer Query: {state['query']}
Company: {state['company_id']}
Customer ID: {state.get('customer_id') or 'Guest'}

Verified Tool Evidence:
{chr(10).join(evidence_summary) if evidence_summary else 'No tools were required or called.'}
"""

    response = invoke_llm_with_fallback([
        SystemMessage(content=system_prompt),
        HumanMessage(content=user_prompt)
    ])

    return {
        "final_response": to_text(response.content)
    }


# -------------------------------------------------------------
# Routing & Graph Construction
# -------------------------------------------------------------

def route_after_planning(state: AgentState) -> str:
    """Decides whether to execute a tool or proceed directly to final response."""
    if state["steps"] >= state["max_steps"]:
        return "respond"

    plan = state.get("plan", {})
    if plan.get("action") == "finish":
        return "respond"

    if plan.get("action") == "tool" and plan.get("tool_name") in TOOL_NAMES:
        return "run_tool"

    return "respond"


def build_customer_support_graph():
    """
    Builds and compiles the high-performance StateGraph workflow.
    Directly routes from run_tool to respond to eliminate redundant planning round-trips.
    """
    builder = StateGraph(AgentState)

    builder.add_node("plan_step", plan_step)
    builder.add_node("run_tool", run_tool)
    builder.add_node("respond", respond)

    builder.add_edge(START, "plan_step")

    builder.add_conditional_edges(
        "plan_step",
        route_after_planning,
        {
            "run_tool": "run_tool",
            "respond": "respond"
        }
    )

    # High-performance pipeline: Once tools execute, synthesize grounded response immediately
    builder.add_edge("run_tool", "respond")
    builder.add_edge("respond", END)

    return builder.compile()


# Global compiled agent workflow
agent_workflow = build_customer_support_graph()


# -------------------------------------------------------------
# End-to-End Production Agent Runner (With Cache, Metrics & Guardrails)
# -------------------------------------------------------------

def run_production_agent(
    company_id: str,
    query: str,
    customer_id: Optional[str] = None
) -> Dict[str, Any]:
    """
    Executes the customer support pipeline:
    1. Checks multi-tenant semantic cache.
    2. Runs LangGraph agent with safety controls.
    3. Redacts sensitive PII.
    4. Validates citations against verified sources.
    5. Logs real metrics to SQLite.
    6. Stores verified response in cache.
    """
    start_time = time.time()
    safety_guardrails.reset_cost()

    # Step 1: Check multi-tenant semantic cache
    cached = semantic_cache.get(company_id=company_id, query=query, customer_id=customer_id)
    if cached:
        elapsed = time.time() - start_time
        platform_metrics.log_query(
            company_id=company_id,
            query=query,
            total_latency=elapsed,
            steps=0,
            tools_used=["cache"],
            from_cache=True
        )
        return {
            "query": query,
            "company_id": company_id,
            "response": cached["response"],
            "sources": cached.get("sources", []),
            "from_cache": True,
            "cache_type": cached.get("cache_type"),
            "latency_seconds": round(elapsed, 4)
        }

    # Step 2: Initialize Agent State
    initial_state: AgentState = {
        "company_id": company_id,
        "customer_id": customer_id,
        "query": query,
        "messages": [HumanMessage(content=query)],
        "tools_results": [],
        "sources": [],
        "steps": 0,
        "max_steps": 10,
        "final_response": ""
    }

    try:
        # Step 3: Run LangGraph Agent
        result = agent_workflow.invoke(initial_state)
        raw_response = to_text(result.get("final_response", ""))

        # Step 4: Safety Guardrails (PII Masking & Step limits)
        safety_guardrails.check_step_limit(result.get("steps", 0))
        masked_response = safety_guardrails.mask_pii(raw_response)

        # Step 5: Citation validation
        sources = result.get("sources", [])
        citation_check = safety_guardrails.validate_citations(masked_response, sources)

        elapsed = time.time() - start_time

        # Collect tools used
        tools_used = [r.get("tool", "unknown") for r in result.get("tools_results", [])]

        # Step 6: Log Telemetry to Database
        platform_metrics.log_query(
            company_id=company_id,
            query=query,
            total_latency=elapsed,
            steps=result.get("steps", 0),
            tools_used=tools_used,
            from_cache=False
        )

        # Step 7: Cache response (only if not an integration error/unconfigured)
        if "unconfigured" not in masked_response.lower() and "error" not in masked_response.lower():
            semantic_cache.set(
                company_id=company_id,
                query=query,
                response=masked_response,
                sources=sources,
                customer_id=customer_id
            )

        return {
            "query": query,
            "company_id": company_id,
            "customer_id": customer_id,
            "response": masked_response,
            "sources": sources,
            "grounded": citation_check.get("grounded", False),
            "citations": citation_check.get("verified_citations", []),
            "from_cache": False,
            "steps": result.get("steps", 0),
            "latency_seconds": round(elapsed, 4)
        }

    except Exception as e:
        elapsed = time.time() - start_time
        err_str = str(e)
        logger.error(f"Agent execution failed for query '{query}': {err_str}", exc_info=True)
        platform_metrics.log_query(
            company_id=company_id,
            query=query,
            total_latency=elapsed,
            steps=initial_state.get("steps", 0),
            tools_used=[],
            from_cache=False,
            error=err_str
        )
        if "RESOURCE_EXHAUSTED" in err_str or "429" in err_str:
            clean_response = "The Gemini API quota for this key has been temporarily reached. Please retry shortly or check your Gemini plan."
        else:
            clean_response = f"An error occurred while processing your request: {err_str}"

        return {
            "query": query,
            "company_id": company_id,
            "response": clean_response,
            "sources": [],
            "from_cache": False,
            "error": err_str,
            "latency_seconds": round(elapsed, 4)
        }
