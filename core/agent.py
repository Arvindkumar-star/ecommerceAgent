AVAILABLE_TOOLS = [
    {
        "name": "retrieve_company_knowledge",
        "description": "Searches the authenticated company's uploaded documents (policies, product manuals, FAQs, warranties). Use for answering policy, terms, shipping, or general business questions."
    },
    {
        "name": "get_order_details",
        "description": "Fetches verified order status, delivery date, tracking, and items from the live e-commerce system. Requires 'order_id'."
    },
    {
        "name": "check_inventory",
        "description": "Queries the live inventory system for real-time stock levels of a product. Requires 'product_id'."
    },
    {
        "name": "check_return_eligibility",
        "description": "Evaluates return eligibility by verifying real order delivery date against verified company return policy. Requires 'order_id'."
    }
]

TOOL_NAMES = {t["name"] for t in AVAILABLE_TOOLS}


def execute_tool_with_context(
    tool_name: str,
    tool_args: Dict[str, Any],
    company_id: str,
    customer_id: Optional[str]
) -> Dict[str, Any]:
    """
    Executes tool with company_id and customer_id automatically injected.
    Never relies on user-supplied or invented company context.
    """
    if tool_name not in TOOL_NAMES:
        return {
            "error": f"Tool '{tool_name}' not found.",
            "source": "tool_executor"
        }

    try:
        if tool_name == "retrieve_company_knowledge":
            query = tool_args.get("query") or tool_args.get("search_query") or ""
            res = knowledge_base.retrieve_company_knowledge(company_id=company_id, query=query)
            return {"data": res, "tool": tool_name, "source": "knowledge_base"}

        elif tool_name == "get_order_details":
            order_id = str(tool_args.get("order_id", "")).replace("#", "").strip()
            res = get_order_details(order_id=order_id, company_id=company_id, customer_id=customer_id)
            return {"data": res, "tool": tool_name, "source": "orders_api"}

        elif tool_name == "check_inventory":
            product_id = str(tool_args.get("product_id", "")).replace("#", "").strip()
            res = check_inventory(product_id=product_id, company_id=company_id)
            return {"data": res, "tool": tool_name, "source": "inventory_api"}

        elif tool_name == "check_return_eligibility":
            order_id = str(tool_args.get("order_id", "")).replace("#", "").strip()
            reason = tool_args.get("reason")
            res = check_return_eligibility(
                order_id=order_id,
                company_id=company_id,
                customer_id=customer_id,
                reason=reason
            )
            return {"data": res, "tool": tool_name, "source": "return_eligibility"}

        else:
            return {"error": f"Unknown tool: {tool_name}", "source": "tool_executor"}

    except Exception as e:
        logger.error(f"Error executing tool {tool_name}: {str(e)}", exc_info=True)
        return {"error": str(e), "source": tool_name}


