CANDIDATE_MODELS = [
    os.getenv("GEMINI_MODEL", "gemini-3.5-flash-lite"),
    "gemini-3.5-flash-lite",
    "gemini-3.1-flash-lite",
    "gemini-flash-latest"
]

def get_llm(model_name: Optional[str] = None):
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        raise ValueError("GEMINI_API_KEY environment variable is not set.")
    chosen_model = model_name or CANDIDATE_MODELS[0]
    return ChatGoogleGenerativeAI(
        model=chosen_model,
        google_api_key=api_key,
        temperature=0,
        max_retries=1
    )


def invoke_llm_with_fallback(messages: Any, structured_class=None) -> Any:
    """Invokes LLM with automatic fallback across models if quota is exhausted."""
    last_err = None
    for model_name in CANDIDATE_MODELS:
        try:
            llm = get_llm(model_name)
            if structured_class:
                target = llm.with_structured_output(structured_class)
            else:
                target = llm
            return target.invoke(messages)
        except Exception as e:
            err_str = str(e)
            last_err = e
            if "RESOURCE_EXHAUSTED" in err_str or "UNAVAILABLE" in err_str or "503" in err_str or "429" in err_str:
                logger.warning(f"Model {model_name} quota/capacity issue: {err_str[:80]}. Falling back to next model...")
                continue
            raise e
    raise last_err


def to_text(content: Any) -> str:
    """Safely normalizes LLM content (string or block list) to plain string."""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for block in content:
            if isinstance(block, dict):
                parts.append(block.get("text", ""))
            else:
                parts.append(str(block))
        return "".join(parts)
    return str(content)


